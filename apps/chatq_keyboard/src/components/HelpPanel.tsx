      <Text style={ui.text}>AI 生成：只有主动点生成时，才将本次消息或背景、所选人设与关系场景直接提交到你配置的 API 供应商；独立 AI 对话还会携带本会话最近的上下文（可以关闭或重置）。这些请求不经过聊商服务器。请勿填写密码、验证码等敏感信息。</Text>
